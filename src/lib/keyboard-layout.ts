// Исправление запроса, набранного не в той раскладке клавиатуры.
//
// Частая ситуация: пользователь забыл переключить раскладку и печатает русский
// текст английскими буквами. Физически нажимаются те же клавиши, поэтому
// «уволили с работы» превращается в «edjkbkb c hf,jns». Обычный поиск и LLM такую
// латинскую «абракадабру» не понимают. Здесь мы переводим её обратно в кириллицу
// по раскладке ЙЦУКЕН (US QWERTY -> русская клавиатура).

// Каждой латинской клавише соответствует русская буква на той же физической клавише.
const EN_TO_RU: Record<string, string> = {
  q: "й", w: "ц", e: "у", r: "к", t: "е", y: "н", u: "г", i: "ш", o: "щ", p: "з", "[": "х", "]": "ъ",
  a: "ф", s: "ы", d: "в", f: "а", g: "п", h: "р", j: "о", k: "л", l: "д", ";": "ж", "'": "э",
  z: "я", x: "ч", c: "с", v: "м", b: "и", n: "т", m: "ь", ",": "б", ".": "ю", "/": ".",
  "`": "ё",
  Q: "Й", W: "Ц", E: "У", R: "К", T: "Е", Y: "Н", U: "Г", I: "Ш", O: "Щ", P: "З", "{": "Х", "}": "Ъ",
  A: "Ф", S: "Ы", D: "В", F: "А", G: "П", H: "Р", J: "О", K: "Л", L: "Д", ":": "Ж", '"': "Э",
  Z: "Я", X: "Ч", C: "С", V: "М", B: "И", N: "Т", M: "Ь", "<": "Б", ">": "Ю", "?": ",",
  "~": "Ё"
};

// Переводит КАЖДЫЙ символ по раскладке. Цифры, пробелы и то, чего нет в карте,
// оставляем как есть.
export function fixKeyboardLayout(text: string): string {
  let result = "";
  for (const char of text) {
    result += EN_TO_RU[char] ?? char;
  }
  return result;
}

const CYRILLIC = /[а-яё]/i;
const LATIN_LETTER = /[a-z]/i;

// Исправляем раскладку только когда это действительно похоже на «забыл переключить»:
// в тексте нет ни одной кириллической буквы, но есть латинские. Если кириллица уже
// есть — считаем, что человек пишет по-русски (с опечатками — их разберут поиск и LLM),
// и ничего не трогаем, чтобы случайно не испортить нормальный запрос.
export function maybeFixKeyboardLayout(text: string): string {
  if (!text) return text;
  if (CYRILLIC.test(text)) return text;
  if (!LATIN_LETTER.test(text)) return text;
  return fixKeyboardLayout(text);
}
