export function canonicalHarantQuestionCategoryName(category: string): HarantQuestionCategory {
  const normalized = normalizeHarantCategoryName(category);
  const direct = HARANT_QUESTION_CATEGORIES.find((item) => normalizeHarantCategoryName(item) === normalized);
  if (direct) return direct;

  const alias = Object.entries(HARANT_QUESTION_CATEGORY_PRIMARY_ALIASES).find(([source]) => normalizeHarantCategoryName(source) === normalized);
  return alias?.[1] ?? "Прочие";
}

export function getHarantSpecializationAliases(category: string) {
  return HARANT_QUESTION_CATEGORY_SPECIALIZATION_ALIASES[canonicalHarantQuestionCategoryName(category)] ?? ["Прочие"];
}

export function normalizeHarantCategoryName(value: string) {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/giu, " ")
    .replace(/\s+/g, " ")
    .trim();
}
