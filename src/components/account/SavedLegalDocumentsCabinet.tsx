"use client";

import Link from "next/link";
import { useCallback, useEffect, useState } from "react";
import type { DocumentResultV1 } from "@/lib/document-result-contract";

type Summary = {
  versionId: string; documentTitle: string; categorySlug: string;
  routeSlug: string; documentSlug: string; scenarioKey: string;
  resultKind: string; requiresLegalReview: boolean; createdAt: string;
};
type State = "loading" | "ready" | "error";

export function SavedLegalDocumentsCabinet() {
  const [documents, setDocuments] = useState<Summary[]>([]);
  const [query, setQuery] = useState("");
  const [category, setCategory] = useState("");
  const [state, setState] = useState<State>("loading");
  const [message, setMessage] = useState("");
  const [selected, setSelected] = useState<DocumentResultV1 | null>(null);
  const [busyId, setBusyId] = useState<string | null>(null);

  const reload = useCallback(async () => {
    try {
      const response = await fetch("/api/account/documents/", { cache: "no-store" });
      const data = await response.json() as { documents?: Summary[]; message?: string };
      if (!response.ok || !data.documents) throw new Error(data.message || "Не удалось получить список.");
      setDocuments(data.documents);
      setState("ready");
    } catch (error) {
      setState("error");
      setMessage(error instanceof Error ? error.message : "Архив недоступен.");
    }
  }, []);

  useEffect(() => { void reload(); }, [reload]);

  async function open(versionId: string) {
    setBusyId(versionId); setMessage("");
    try {
      const response = await fetch(`/api/account/documents/${encodeURIComponent(versionId)}/`, { cache: "no-store" });
      const data = await response.json() as { documentResult?: DocumentResultV1; message?: string };
      if (!response.ok || !data.documentResult) throw new Error(data.message || "Версия не найдена.");
      setSelected(data.documentResult);
    } catch (error) { setMessage(error instanceof Error ? error.message : "Версию открыть не удалось."); }
    finally { setBusyId(null); }
  }

  async function remove(versionId: string) {
    if (!window.confirm("Удалить эту сохранённую версию без возможности восстановления?")) return;
    setBusyId(versionId); setMessage("");
    try {
      const response = await fetch(`/api/account/documents/${encodeURIComponent(versionId)}/`, { method: "DELETE" });
      if (!response.ok) throw new Error("Не удалось удалить версию.");
      if (selected?.versionId === versionId) setSelected(null);
      await reload();
    } catch (error) { setMessage(error instanceof Error ? error.message : "Удаление не выполнено."); }
    finally { setBusyId(null); }
  }

  async function exportPdf() {
    if (!selected) return;
    try {
      // A neutral archive copy of the saved text, not an official form or
      // necessarily the PDF originally generated by the specialised wizard.
      const blob = selected.categorySlug === "semya-i-deti"
        ? await (await import("@/lib/versioned-family-result-pdf")).createVersionedFamilyResultPdfBlob(selected)
        : await (await import("@/lib/labor-document-export")).createLaborDocumentPdfBlob({
            statusLabel: "АРХИВНАЯ КОПИЯ — НЕ ГОТОВА К ПОДАЧЕ",
            documentTitle: selected.documentTitle, documentText: selected.documentText,
            rules: [], nextSteps: [],
            reviewedAt: selected.legalRegistryReviewedAt, versionId: selected.versionId
          });
      const url = URL.createObjectURL(blob);
      const anchor = window.document.createElement("a");
      anchor.href = url;
      anchor.download = `pravopoisk-${selected.versionId}.pdf`;
      anchor.click();
      URL.revokeObjectURL(url);
    } catch { setMessage("PDF из архивной копии сформировать не удалось."); }
  }

  const filtered = documents.filter((item) =>
    (!category || item.categorySlug === category) &&
    (!query.trim() || [item.documentTitle, item.routeSlug, item.documentSlug, item.versionId].join(" ").toLocaleLowerCase("ru").includes(query.trim().toLocaleLowerCase("ru")))
  );

  return <section className="rounded-xl border border-line bg-white p-4 shadow-sm sm:p-6">
    <p className="text-sm leading-6 text-zinc-700">Сохраняются только версии, которые вы явно добавили в архив. Текст зашифрован на сервере, доступен только вашей учётной записи. Удаление окончательное. Юридическая проверка не выполняется при сохранении.</p>
    <div className="mt-4 flex flex-wrap gap-3">
      <Link href="/documents/" className="inline-flex min-h-11 items-center rounded-md bg-trust px-4 py-2 text-sm font-semibold text-white">Подготовить документ</Link>
      <button type="button" onClick={() => { setState("loading"); void reload(); }} className="min-h-11 rounded-md border border-line px-4 py-2 text-sm font-semibold">Обновить список</button>
    </div>
    {state === "ready" && documents.length > 0 ? <div className="mt-5 grid gap-3 sm:grid-cols-2">
      <label className="grid gap-1 text-sm font-medium">Поиск по сохранённым версиям
        <input type="search" value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Название документа или номер версии" className="min-h-11 rounded-md border border-line px-3 py-2" />
      </label>
      <label className="grid gap-1 text-sm font-medium">Раздел права
        <select value={category} onChange={(event) => setCategory(event.target.value)} className="min-h-11 rounded-md border border-line bg-white px-3 py-2">
          <option value="">Все разделы</option>
          <option value="semya-i-deti">Семейное право</option>
          <option value="trudovoe-pravo">Трудовое право</option>
        </select>
      </label>
      <p className="text-sm text-zinc-600 sm:col-span-2" role="status">Найдено версий: {filtered.length} из {documents.length}</p>
    </div> : null}
    {state === "loading" ? <p role="status" className="mt-5">Загрузка зашифрованного архива…</p> : null}
    {state === "error" ? <p role="alert" className="mt-5 text-red-800">{message}</p> : null}
    {state === "ready" && !documents.length ? <p className="mt-6 rounded-md bg-zinc-50 p-4 text-sm">Сохранённых документов пока нет. Сформируйте документ и нажмите «Сохранить в мои документы».</p> : null}
    {state === "ready" && documents.length > 0 && filtered.length === 0 ? <p className="mt-5 text-sm" role="status">По выбранным условиям документов не найдено.</p> : null}
    {state === "ready" && filtered.length ? <ol className="mt-6 grid gap-3">
      {filtered.map((item) => <li key={item.versionId} className="rounded-lg border border-line p-4">
        <h2 className="break-words text-base font-semibold">{item.documentTitle}</h2>
        <p className="mt-2 text-xs text-zinc-600">Сохранено: {new Date(item.createdAt).toLocaleString("ru-RU")}; статус: не подтверждена готовность к подаче</p>
        <p className="mt-1 break-all text-xs text-zinc-500">Версия: {item.versionId}</p>
        <div className="mt-3 flex flex-wrap gap-3">
          <button type="button" onClick={() => void open(item.versionId)} disabled={busyId !== null} className="min-h-11 rounded-md bg-trust px-4 py-2 text-sm font-semibold text-white disabled:opacity-60">Открыть версию</button>
          <Link href={`/documents/${encodeURIComponent(item.documentSlug)}/`} className="inline-flex min-h-11 items-center rounded-md border border-line px-4 py-2 text-sm font-semibold">Страница документа</Link>
          <button type="button" onClick={() => void remove(item.versionId)} disabled={busyId !== null} className="min-h-11 rounded-md border border-red-300 px-4 py-2 text-sm font-semibold text-red-800 disabled:opacity-60">Удалить</button>
        </div>
      </li>)}
    </ol> : null}
    {selected ? <section className="mt-8 border-t border-line pt-6" aria-label="Сохранённая версия документа">
      <h2 className="text-xl font-semibold">{selected.documentTitle}</h2>
      <p className="mt-2 text-sm text-amber-800">Архивный текст — не юридически проверенный и не готовый к подаче документ. PDF будет создан заново из сохранённого текста; оформление исходного генератора может отличаться.</p>
      <p className="mt-2 break-all text-xs text-zinc-500">ID версии: {selected.versionId}</p>
      <pre className="mt-4 max-h-[70vh] overflow-auto whitespace-pre-wrap break-words rounded-md border border-line bg-zinc-50 p-4 font-sans text-sm leading-6">{selected.documentText}</pre>
      <button type="button" onClick={() => void exportPdf()} className="mt-4 min-h-11 rounded-md bg-trust px-4 py-2 text-sm font-semibold text-white">Скачать архивную копию PDF</button>
    </section> : null}
    {message && state !== "error" ? <p role="alert" className="mt-4 text-sm text-red-800">{message}</p> : null}
  </section>;
}
