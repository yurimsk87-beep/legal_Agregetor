function cleanSpaces(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

function normalize(value) {
  return cleanSpaces(value)
    .toLocaleLowerCase("ru-RU")
    .replace(/[ё]/g, "е")
    .replace(/[^a-zа-я0-9]+/giu, " ")
    .trim();
}

function wordCount(value) {
  return cleanSpaces(value).match(/[a-zа-я0-9ё]+/giu)?.length ?? 0;
}

function ensureQuestion(value) {
  const text = cleanSpaces(value).replace(/[?.!]+$/g, "");
  return text ? `${text}?` : "";
}

function titleHasBadShape(title) {
  const text = cleanSpaces(title);
  const key = normalize(text);
  const count = wordCount(text);

  return (
    count < 5 ||
    count > 16 ||
    /^что делать($|\s|,|\?)/iu.test(text) ||
    /^как быть($|\s|\?)/iu.test(text) ||
    /^как выйти из положения/iu.test(text) ||
    /^как можно урегулировать этот вопрос/iu.test(text) ||
    /с вами связаться/iu.test(text) ||
    /судебная практика выигранных дел/iu.test(text) ||
    /плотит|будети|найду отец|как была назначена я операция|как заявлено|как сделать есть ли образец/iu.test(text) ||
    /\b(при|и|или|в|на|по|с|без|для|как|что)$/iu.test(key)
  );
}

