function matchingRule(row) {
  const title = row.rawTitle || "";
  const question = row.rawQuestion || "";
  return rules.find((rule) => {
    if (rule.title && !rule.title.test(title)) return false;
    if (rule.question && !rule.question.test(question)) return false;
    return true;
  });
}

const fixedRows = [];
const changed = [];
const removed = [];

for (const [index, row] of rows.entries()) {
  const rule = matchingRule(row);
  if (rule?.remove) {
    removed.push({ row: index + 1, title: row.rawTitle, reason: rule.reason });
    continue;
  }

  const next = { ...row };
  if (rule?.newTitle) {
    next.rawTitle = ensureQuestion(rule.newTitle);
    if (rule.category) next.rawCategory = rule.category;
    next.additionalCategory = "";
    changed.push({ row: index + 1, from: row.rawTitle, to: next.rawTitle });
  }

  fixedRows.push(next);
}

const remainingBad = fixedRows
  .map((row, index) => ({ index: index + 1, title: row.rawTitle, question: row.rawQuestion, category: row.rawCategory }))
  .filter((row) => titleHasBadShape(row.title))
  .filter((row) => {
    // Keep concise but valid legal titles. The audit focuses on broken/generic residue.
    const title = cleanSpaces(row.title);
    return (
      /^что делать(,|\s|\?)/iu.test(title) ||
      /^как быть(,|\s|\?)/iu.test(title) ||
      /с вами связаться|судебная практика выигранных дел|плотит|будети|найду отец|как была назначена я операция|как заявлено|как сделать есть ли образец/iu.test(title) ||
      /\b(при|и|или|в|на|по|с|без|для|как|что)$/iu.test(normalize(title))
    );
  });

const report = {
  apply,
  sourceRows: rows.length,
  outputRows: fixedRows.length,
  changed: changed.length,
  removed: removed.length,
  remainingBad: remainingBad.length,
  changedPreview: changed.slice(0, 80),
  removed,
  remainingBadPreview: remainingBad.slice(0, 50)
};

if (apply) {
  payload.rows = fixedRows;
  writeFileSync(inputPath, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
}

