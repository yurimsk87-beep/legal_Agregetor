// Content-based legal-question classifier.
//
// Why this exists: the scraped source category (pravoved breadcrumb) reflects the
// ANSWERING LAWYER's specialization, not the question topic — so a credit question
// answered by a military lawyer ends up tagged "Военное право". The only reliable
// signal is the question text itself. This module scores the text against curated,
// high-precision keyword rules and returns the best HARANT category.
//
// Cyrillic gotcha: JS \b / \w are ASCII-only, so `\bсво\b` does NOT word-bound
// Russian text and `сво` as a bare substring matches "свои", "своего" (the exact
// bug that inflated "Военное право"). Short ambiguous tokens are therefore matched
// as WHOLE WORDS via a token set; stems use explicit [а-я] classes, never \w.

