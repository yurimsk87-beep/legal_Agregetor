const DEFAULT_CATEGORY: HarantQuestionCategory = "Гражданские дела";

function normalizeText(value: string): string {
  return (value || "").toLowerCase().replace(/ё/g, "е");
}

function tokenize(text: string): Set<string> {
  return new Set(text.match(/[a-zа-я0-9-]+/g) ?? []);
}

export type ClassifyResult = {
  category: HarantQuestionCategory;
  score: number;
  scores: Record<string, number>;
};

export function classifyLegalQuestion(title: string, body: string): ClassifyResult {
  const text = normalizeText(`${title ?? ""}\n${body ?? ""}`);
  const tokens = tokenize(text);

  let best: HarantQuestionCategory = DEFAULT_CATEGORY;
  let bestScore = 0;
  const scores: Record<string, number> = {};

  for (const { category, rules } of CATEGORY_RULES) {
    let score = 0;
    for (const rule of rules) {
      let matched = false;
      if (rule.re) {
        for (const re of rule.re) {
          if (re.test(text)) {
            matched = true;
            break;
          }
        }
      }
      if (!matched && rule.word) {
        for (const w of rule.word) {
          if (tokens.has(w)) {
            matched = true;
            break;
          }
        }
      }
      if (matched) score += rule.weight;
    }
    if (score > 0) scores[category] = score;
    // Strict ">" keeps the earlier (more specific) category on ties.
    if (score > bestScore) {
      bestScore = score;
      best = category;
    }
  }

  return { category: bestScore > 0 ? best : DEFAULT_CATEGORY, score: bestScore, scores };
}

