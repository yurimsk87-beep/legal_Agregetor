def main() -> None:
    short_rows = {row: len(text) for row, text in DESCRIPTIONS.items() if len(text) < 350}
    if short_rows:
        raise ValueError(f"Descriptions shorter than 350 characters: {short_rows}")

    if not SOURCE_PATH.exists():
        raise FileNotFoundError(SOURCE_PATH)

    BACKUP_PATH.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOURCE_PATH, BACKUP_PATH)

    workbook = openpyxl.load_workbook(SOURCE_PATH)
    worksheet = workbook.active

    for row_number, description in DESCRIPTIONS.items():
        cell = worksheet.cell(row=row_number, column=1)
        cell.value = description
        cell.alignment = Alignment(wrap_text=True, vertical="top")

    workbook.save(SOURCE_PATH)

    for row_number, description in sorted(DESCRIPTIONS.items()):
        print(f"row {row_number}: {len(description)} chars")
    print(f"backup: {BACKUP_PATH}")
    print(f"updated: {SOURCE_PATH}")


if __name__ == "__main__":
    main()
