def direct_question_title(question):
    candidates = []
    for sentence in split_sentences(question):
        sentence = clean_spaces(sentence)
        if "?" in sentence:
            candidates.append(sentence.split("?")[0])
        match = QUESTION_STARTS.search(sentence)
        if match:
            before = normalize(sentence[: match.start()])
            if before and not re.search(r"(вопрос|спрашиваю|интересует)$", before):
                continue
            if before.endswith("так"):
                continue
            candidates.append(sentence[match.start():])

    scored = []
    for candidate in candidates:
        text = strip_intro(candidate)
        text = re.sub(r"^(и|или)\s+", "", text, flags=re.IGNORECASE)
        text = re.sub(r"\s+", " ", text).strip(" ,;:-?.!")
        if not text:
            continue
        text = trim_title_words(text, 14)
        if low_quality_direct_title(text):
            continue
        key = normalize(text)
        score = 0
        if QUESTION_STARTS.search(text):
            score += 8
        if re.search(r"суд|иск|договор|выплат|штраф|долг|увол|военн|сво|квартир|налог|пристав|наслед|алимент|полици|ввк|банк|арест|компенсац|расторж|возврат|миграц|гражданств", key):
            score += 8
        if 6 <= word_count(text) <= 14:
            score += 5
        scored.append((score, text))

    if not scored:
        return ""
    scored.sort(key=lambda item: item[0], reverse=True)
    title = ensure_question(scored[0][1])
    return "" if bad_title(title) else title


def generate_title(question, category):
    title = direct_question_title(question)
    if title and not bad_title(title):
        return title
    title = specific_focused_title(question, category)
    if title and not bad_title(ensure_question(title)):
        return ensure_question(title)
    return ensure_question(fallback_title(category, question))


def duplicate_key(value):
    return normalize(value)[:500]


def find_column(headers, names):
    normalized = [normalize(header) for header in headers]
    wanted = {normalize(name) for name in names}
    for index, header in enumerate(normalized):
        if header in wanted:
            return index
    return -1


def read_source_rows():
    workbook = load_workbook(INPUT_XLSX, read_only=True)
    sheet = workbook.active
    rows = sheet.iter_rows(values_only=True)
    headers = list(next(rows))
    category_index = find_column(headers, ["Категория вопроса", "Категория права", "rawCategory"])
    question_index = find_column(headers, ["Вопрос", "rawQuestion"])
    answer_index = find_column(headers, ["Ответ юриста", "Улучшенный ответ юриста", "lawyerAnswer"])

    for name, index in {"category": category_index, "question": question_index, "answer": answer_index}.items():
        if index < 0:
            raise RuntimeError(f"Required column not found: {name}")

    for row_number, values in enumerate(rows, start=2):
        yield {
            "rowNumber": row_number,
            "category": values[category_index],
            "question": values[question_index],
            "answer": values[answer_index],
        }


def write_enriched_xlsx(rows):
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Harant Q&A"
    headers = ["Вопрос", "Ответ юриста", "Категория права", "Дополнительная категория", "SEO-заголовок", "Улучшенный ответ юриста"]
    sheet.append(headers)
    for row in rows:
        sheet.append([
            row["rawQuestion"],
            row["sourceAnswer"],
            row["rawCategory"],
            row["additionalCategory"],
            row["rawTitle"],
            row["lawyerAnswer"],
        ])

    header_fill = PatternFill("solid", fgColor="1F4E78")
    header_font = Font(color="FFFFFF", bold=True)
    for cell in sheet[1]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    widths = [70, 85, 28, 28, 55, 90]
    for index, width in enumerate(widths, start=1):
        sheet.column_dimensions[chr(64 + index)].width = width
    for row in sheet.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
    sheet.freeze_panes = "A2"
    workbook.save(OUTPUT_XLSX)


def main():
    global INPUT_XLSX, OUTPUT_JSON, OUTPUT_XLSX
    args = parse_args()
    INPUT_XLSX = args.input
    OUTPUT_JSON = args.output_json
    OUTPUT_XLSX = args.output_xlsx

    prepared = []
    seen_questions = set()
    seen_titles = set()
    stats = Counter()
    bad_examples = []

    for source in read_source_rows():
        stats["sourceRows"] += 1
        question = clean_question(source["question"])
        answer = clean_answer(source["answer"])
        if not question or len(question) < 25:
            stats["skippedShortQuestion"] += 1
            continue
        if not answer or weak_answer(answer):
            stats["skippedWeakAnswer"] += 1
            continue

        question_key = duplicate_key(question)
        if question_key in seen_questions:
            stats["skippedDuplicateQuestion"] += 1
            continue
        seen_questions.add(question_key)

        category = infer_category(source["category"], question)
        title = generate_title(question, category)
        if bad_title(title):
            stats["skippedBadTitle"] += 1
            bad_examples.append({"row": source["rowNumber"], "title": title, "question": question[:220]})
            continue

        title_key = normalize(title)
        if title_key in seen_titles:
            stats["skippedDuplicateTitle"] += 1
            continue
        seen_titles.add(title_key)

        prepared.append({
            "rawQuestion": question,
            "sourceAnswer": clean_spaces(source["answer"]),
            "rawCategory": category,
            "additionalCategory": "",
            "rawTitle": title,
            "lawyerAnswer": answer,
        })

    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_XLSX.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_JSON.write_text(json.dumps({"rows": prepared}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_enriched_xlsx(prepared)

    stats["outputRows"] = len(prepared)
    stats["badExamples"] = len(bad_examples)
    report = dict(stats)
    report["categoryCounts"] = Counter(row["rawCategory"] for row in prepared).most_common()
    report["badExamplesPreview"] = bad_examples[:20]
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
