QUESTION_STARTS = re.compile(
    r"(можно ли|могу ли я|можем ли|имею ли я право|имеет ли право|законно ли|правомерно ли|что делать|как |куда |где |кто |какие |какой |положен[аы]? ли|нужно ли|должен ли|должна ли|обязан ли|обязана ли|будет ли|могут ли)",
    re.IGNORECASE,
)


def direct_question_title(question):
    candidates = []
    for sentence in split_sentences(question):
        if "?" in sentence:
            candidates.append(sentence)
        match = QUESTION_STARTS.search(sentence)
        if match:
            candidates.append(sentence[match.start() :])

    scored = []
    for candidate in candidates:
        text = strip_intro(candidate)
        text = re.sub(r"^(и|или)\s+", "", text, flags=re.IGNORECASE)
        text = re.sub(r"\s+", " ", text).strip(" ,;:-")
        if not text:
            continue
        score = 0
        key = normalize(text)
        if QUESTION_STARTS.search(text):
            score += 8
        if re.search(r"суд|иск|договор|выплат|штраф|долг|увол|военн|сво|квартир|налог|пристав|наслед|алимент|полици|ввк|банк|арест|компенсац|расторж|возврат|миграц|гражданств", key):
            score += 7
        count = word_count(text)
        if 6 <= count <= 14:
            score += 5
        if count < 5 or count > 18:
            score -= 6
        if re.search(r"подскажите|пожалуйста|с вами связаться|нужна консультация|добрый день", key):
            score -= 8
        scored.append((score, text))

    if not scored:
        return ""
    scored.sort(key=lambda item: item[0], reverse=True)
    best = trim_title_words(scored[0][1], 14)
    return ensure_question(best)


def generate_title(question, category):
    title = direct_question_title(question)
    if title and not bad_title(title):
        return title
    title = focused_title(question, category)
    return ensure_question(title)


