def clean_spaces(value):
    text = re.sub(r"\s+", " ", html.unescape(str(value or "")).replace("\xa0", " ")).strip()
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    text = re.sub(r"([,.;:!?])(?=\S)", r"\1 ", text)
    return text.strip()


def normalize(value):
    text = clean_spaces(value).lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-я0-9]+", " ", text, flags=re.IGNORECASE)
    return clean_spaces(text)


def words(value):
    return re.findall(r"[A-Za-zА-Яа-яЁё0-9]+", str(value or ""))


def word_count(value):
    return len(words(value))


def sentence_case(value):
    text = clean_spaces(value)
    return text[:1].upper() + text[1:] if text else ""


def ensure_question(value):
    text = clean_spaces(value)
    text = re.sub(r"[?.!]+$", "", text).strip(" ,;:-")
    return f"{sentence_case(text)}?" if text else ""


