def strip_intro(value):
    text = fix_typos(value)
    text = re.sub(
        r"^(здравствуйте|добрый день|добрый вечер|доброе утро|приветствую)[,!\.\s-]*",
        "",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"^(подскажите|скажите|пожалуйста|прошу подсказать|нужна консультация)[,!\.\s-]*",
        "",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(r"^у меня\s+(такой|следующий)?\s*вопрос[:,]?\s*", "", text, flags=re.IGNORECASE)
    return clean_spaces(text)


def split_sentences(value):
    text = strip_intro(value)
    parts = re.split(r"(?<=[?!.])\s+|\n+", text)
    return [clean_spaces(part) for part in parts if clean_spaces(part)]


def trim_title_words(value, maximum=14):
    parts = words(value)
    if len(parts) <= maximum:
        return clean_spaces(value).rstrip("?.!")
    return " ".join(parts[:maximum])


def bad_title(value):
    title = clean_spaces(value)
    key = normalize(title)
    count = word_count(title)
    if not title.endswith("?"):
        return True
    if count < 5 or count > 16:
        return True
    if re.search(r"\b(при|и|или|в|на|по|с|без|для|как|что)$", key, flags=re.IGNORECASE):
        return True
    if re.search(r"^(что делать|что дальше|как быть|как выйти из положения|что делать в данной ситуации|что делать в этой ситуации|что делать дальше мне)\??$", key, flags=re.IGNORECASE):
        return True
    if re.search(r"с вами связаться|напишите в max|напишите в макс|судебная практика выигранных дел", key, flags=re.IGNORECASE):
        return True
    if re.search(r"плотит|будети|найду отец|как была назначена я операция|как заявлено", key, flags=re.IGNORECASE):
        return True
    return False


